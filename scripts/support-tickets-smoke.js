'use strict';
const fs=require('fs');const path=require('path');
const root=path.join(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const assert=(condition,message)=>{if(!condition)throw new Error(message)};
const migration=read('db/migrations/012_support_tickets.sql');
const domain=read('src/support/tickets.js');
const notifications=read('src/support/notifications.js');
const customer=read('src/platform/customer-support.js');
const admin=read('src/platform/admin-support-tickets.js');
const orders=read('src/platform/admin-orders.js');
const nav=read('src/platform/admin-nav.js');
const composition=read('src/platform/admin-route-composition.js');
const router=read('src/platform/router.js');
const operator=read('src/platform/admin-operator-state.js');
const indicator=read('public/js/operator-business-indicators.js');
for(const table of ['support_tickets','support_ticket_messages'])assert(migration.includes(`CREATE TABLE ${table}`),`missing ${table} migration`);
for(const rule of ["status IN ('open','awaiting_staff')","internal_note=FALSE","customer_id=$2"])assert(domain.includes(rule),`support ownership contract missing ${rule}`);
assert(domain.includes('RETURNING id,created_at'),'staff replies must return a stable message identity for notification dedupe');
assert(notifications.includes("type:'support_ticket_reply'")&&notifications.includes('dedupeKey:`support-ticket-reply:${messageId}`'),'ticket reply email must use deduped transactional outbox delivery');
assert(customer.includes("router.use('/account/support',requireCustomer)"),'customer support must require an authenticated customer');
assert(customer.includes('csrf.verify(req)'),'customer support mutations must use CSRF');
assert(admin.includes("router.use('/admin/tickets',gate)"),'admin ticket routes must require admin auth');
assert(admin.includes('csrf.verify(req)'),'admin ticket mutations must use CSRF');
assert(admin.includes("catch(error){console.warn('Support reply notification could not be queued:'"),'notification failure must not invalidate a committed staff reply');
assert(nav.includes("['tickets','Tickets','/admin/tickets']"),'Tickets must be visible in admin navigation');
assert(nav.includes("['orders','Orders','/admin/orders']"),'Orders must be visible in admin navigation');
assert(composition.includes('createAdminSupportTicketsRouter')&&composition.includes('createAdminOrdersRouter'),'admin support/orders must use canonical route composition');
assert(router.includes('createCustomerSupportRouter'),'customer support must be mounted in the customer runtime');
for(const key of ['customers','orders','tickets'])assert(operator.includes(`${key}:`)||operator.includes(`const [customers,orders`),`operator state missing ${key}`);
for(const href of ['/admin/users','/admin/orders','/admin/tickets'])assert(indicator.includes(href),`business indicator missing ${href}`);
assert(indicator.includes('unreadBusinessCount')&&indicator.includes('seen(href)>=updatedAt'),'top-right business indicators must clear after the operator views the relevant area');
assert(orders.includes("source IN ('stripe','paypal')"),'orders view must be provider-backed');
