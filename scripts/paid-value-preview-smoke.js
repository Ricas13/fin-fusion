'use strict';
const assert=require('assert');
const {previewFromEvidence}=require('./paid-value-preview');
const day=86400000,start=Date.UTC(2026,0,1),end=start+30*day;
const contract={checkoutIntentId:'intent',kind:'direct_plan',checkoutMode:'payment',planId:'plan',provider:'stripe',currency:'GBP',priceMinor:6000,discountedMinor:4500,serviceCreditMinor:0};
const row={source:'stripe',billing_mode:'payment',status:'active',service_extension_days:0,term_matches:true,intent_id:'intent',intent_state:'completed',commercial_snapshot:contract,intent_snapshot:contract,plan_id:'plan',currency_snapshot:'GBP',starts_at:new Date(start),current_period_end:new Date(end),as_of:new Date(start+10*day),payment_records:[{gross_amount_minor:'4500',currency:'GBP'}]};
const quote=overrides=>previewFromEvidence({...row,...overrides});
const half=quote({as_of:new Date(start+15*day)});
assert(half.verified);assert.strictEqual(BigInt(half.remainingValueMinor.numerator)/BigInt(half.remainingValueMinor.denominator),2250n);
const future=quote({as_of:new Date(start-day)});
assert.strictEqual(BigInt(future.remainingValueMinor.numerator)/BigInt(future.remainingValueMinor.denominator),4500n);
assert(!quote({as_of:new Date(end)}).verified);
assert(!quote({payment_records:[]}).verified);assert(!quote({payment_records:[...row.payment_records,...row.payment_records]}).verified);
assert(!quote({payment_records:[{gross_amount_minor:'6000',currency:'GBP'}]}).verified,'never infer value from list price');
assert(!quote({payment_records:[{gross_amount_minor:'4500',currency:'USD'}]}).verified);
for(const flag of ['has_extension_history','has_carry_history','has_adverse_incident','has_adverse_financial_history','has_open_plan_change','permanent_or_operator_present'])assert(!quote({[flag]:true}).verified,flag);
assert(!quote({billing_mode:'subscription'}).verified);
assert(!quote({term_matches:false}).verified);
assert(!quote({commercial_snapshot:{...contract,serviceCreditMinor:100}}).verified);
assert(!quote({intent_state:'open'}).verified);
assert(!quote({intent_snapshot:{...contract,discountedMinor:6000}}).verified);
const partial=quote({as_of:new Date(start+1)});
assert(BigInt(partial.remainingValueMinor.numerator)%BigInt(partial.remainingValueMinor.denominator)!==0n,'retain fraction until rounding policy is approved');
console.log('paid value preview smoke: exact cash basis and refusal invariants ok');
