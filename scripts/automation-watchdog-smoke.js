'use strict';
const assert=require('assert');
const {evaluate}=require('./automation-watchdog');
const now=Date.parse('2026-11-28T12:00:00Z');
const ago=minutes=>new Date(now-minutes*60000);
const definitions=[{key:'billing',critical:true},{key:'customer_inactivity',critical:true,mayBeDisabled:true},{key:'stremio_media_index',critical:false}];
const worker={started_at:ago(120),last_heartbeat_at:ago(0.5)};
const good={enabled:true,interval_seconds:300,last_started_at:ago(2),last_completed_at:ago(1),last_outcome:'success',next_run_at:ago(-4)};
const rows=[{...good,job_key:'billing'},{...good,job_key:'customer_inactivity',enabled:false},{...good,job_key:'stremio_media_index'}];
const report=(overrides={})=>evaluate({worker,jobs:rows,definitions,now,...overrides});
assert(report().ok);
assert(!report({worker:null}).ok);
assert(!report({worker:{...worker,last_heartbeat_at:ago(2)}}).ok);
assert(!report({jobs:rows.slice(1)}).ok,'missing critical job');
assert(report({worker:{...worker,started_at:ago(1)},jobs:rows.slice(1)}).ok,'restart grace');
assert(!report({jobs:[{...rows[0],enabled:false},...rows.slice(1)]}).ok,'unexpected disablement');
assert(report({jobs:[{...rows[0],last_started_at:ago(5),last_completed_at:ago(6)},...rows.slice(1)]}).ok,'normal running job');
let stuck=report({jobs:[{...rows[0],last_started_at:ago(31),last_completed_at:ago(32)},...rows.slice(1)]});
assert(!stuck.ok&&stuck.findings.some(f=>f.code==='job_running_too_long'));
let overdue=report({jobs:[{...rows[0],last_started_at:ago(40),last_completed_at:ago(39),next_run_at:ago(34)},...rows.slice(1)]});
assert(!overdue.ok&&overdue.findings.some(f=>f.code==='critical_job_overdue'));
assert(!report({jobs:[{...rows[0],last_outcome:'failed'},...rows.slice(1)]}).ok);
let longIndex=report({jobs:[...rows.slice(0,2),{...rows[2],last_started_at:ago(61),last_completed_at:ago(62)}]});
assert(longIndex.ok&&longIndex.findings.some(f=>f.severity==='warning'&&f.jobKey==='stremio_media_index'));
console.log('independent automation watchdog smoke: ok');
