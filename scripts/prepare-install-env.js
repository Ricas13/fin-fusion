'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const CORE_KEYS = [
  'DATA_ENCRYPTION_KEY',
  'JELLYFIN_ENCRYPTION_KEY',
  'ACTIVITY_ENCRYPTION_KEY',
  'AUTH_ENCRYPTION_KEY',
  'BACKUP_ENCRYPTION_KEY',
  'STREMIO_JELLYFIN_TOKEN_KEY'
];

const RUNTIME_URLS = [
  'APP_DATABASE_URL',
  'AUTOMATION_DATABASE_URL',
  'ACTIVITY_DATABASE_URL',
  'BACKUP_DATABASE_URL',
  'BACKUP_VERIFY_DATABASE_URL'
];

function parseArgs(argv) {
  const options = { envFile: '.env', template: '.env.example' };
  for (const arg of argv) {
    if (arg.startsWith('--env-file=')) options.envFile = arg.slice('--env-file='.length);
    else if (arg.startsWith('--template=')) options.template = arg.slice('--template='.length);
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

function setValue(content, key, value) {
  const line = `${key}=${value}`;
  const re = new RegExp(`^${key}=.*$`, 'm');
  if (!re.test(content)) throw new Error(`Template is missing required setting ${key}`);
  return content.replace(re, line);
}

function randomHex(bytes = 32) {
  return crypto.randomBytes(bytes).toString('hex');
}

function writeAtomic(file, content) {
  const dir = path.dirname(file);
  fs.mkdirSync(dir, { recursive: true });
  const tmp = path.join(dir, `.${path.basename(file)}.${process.pid}.tmp`);
  fs.writeFileSync(tmp, content, { mode: 0o600 });
  fs.renameSync(tmp, file);
  fs.chmodSync(file, 0o600);
}

function backupIdentity() {
  const uid = typeof process.getuid === 'function' ? process.getuid() : null;
  const gid = typeof process.getgid === 'function' ? process.getgid() : null;
  if (!Number.isInteger(uid) || !Number.isInteger(gid)) return { uid: 1000, gid: 1000 };
  if (uid === 0) return { uid: 1000, gid: 1000 };
  return { uid, gid };
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const envFile = path.resolve(options.envFile);
  const templateFile = path.resolve(options.template);

  if (fs.existsSync(envFile)) {
    throw new Error(`Environment file already exists: ${envFile}. Refusing to replace installation secrets.`);
  }
  if (!fs.existsSync(templateFile)) throw new Error(`Environment template not found: ${templateFile}`);

  let content = fs.readFileSync(templateFile, 'utf8');
  const ownerPassword = randomHex(32);
  content = setValue(content, 'POSTGRES_PASSWORD', ownerPassword);
  content = setValue(content, 'DATABASE_URL', `postgres://steamfusion:${ownerPassword}@postgres:5432/steamfusion`);

  // The production deployment helper owns runtime-role credential generation.
  // Keep these blank here so it creates independent passwords for each role.
  for (const key of RUNTIME_URLS) content = setValue(content, key, '');

  const generated = new Set([ownerPassword]);
  for (const key of CORE_KEYS) {
    const value = randomHex(32);
    if (generated.has(value)) throw new Error('Random secret collision while preparing installation');
    generated.add(value);
    content = setValue(content, key, value);
  }

  const sessionSecret = randomHex(48);
  if (generated.has(sessionSecret)) throw new Error('Random session secret collision while preparing installation');
  content = setValue(content, 'SESSION_SECRET', sessionSecret);

  const identity = backupIdentity();
  content = setValue(content, 'BACKUP_PUID', String(identity.uid));
  content = setValue(content, 'BACKUP_PGID', String(identity.gid));

  // Interactive browser setup is the default. Never invent administrator
  // credentials that an operator did not choose.
  content = setValue(content, 'ADMIN_USERNAME', '');
  content = setValue(content, 'ADMIN_EMAIL', '');
  content = setValue(content, 'ADMIN_PASSWORD', '');

  content = `# Generated by CAPTAiNFiN install.sh. Keep this file private.\n${content}`;
  writeAtomic(envFile, content);
  console.log(`Created ${envFile} with independent high-entropy installation secrets.`);
  console.log(`Backup containers will use UID:GID ${identity.uid}:${identity.gid}.`);
  console.log('Administrator credentials remain unset so the secure browser first-run flow can create them.');
}

try { main(); }
catch (error) {
  console.error(`Fresh-install environment preparation failed: ${error.message}`);
  process.exit(1);
}