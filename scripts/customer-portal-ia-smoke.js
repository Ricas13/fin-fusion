'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');

const dashboard=read('views/customer/dashboard.ejs');
const onboarding=read('views/customer/onboarding.ejs');
const nav=read('views/customer/_nav.ejs');
const router=read('src/platform/router.js');
const customerCompositionPath=path.join(root,'src/platform/customer-route-composition.js');
const customerComposition=fs.existsSync(customerCompositionPath)?fs.readFileSync(customerCompositionPath,'utf8'):'';
const acquisition=read('src/platform/customer-plan-acquisition.js');
const publicAuth=read('src/platform/customer-public-auth.js');
const pending=read('src/security/pending-registration.js');
const capacity=read('src/entitlements/plan-capacity.js');
const storefront=read('src/platform/storefront.js');
const paymentReturn=read('src/platform/customer-payment-return.js');
const checkout=read('src/platform/flexible-checkout.js');
const stremio=read('views/customer/stremio-dashboard.ejs');
const history=read('src/platform/customer-history.js');
const activity=read('src/platform/customer-activity.js');
const customerPortalCss=read('public/css/customer-portal.css');

for(const label of ['Home','Setup','Plan &amp; billing','Activity','Account'])assert(nav.includes(label),`customer navigation missing ${label}`);
for(const conditional of ['showBenefits','showHelp'])assert(nav.includes(conditional),`customer navigation must keep ${conditional} conditional`);
assert(!nav.includes('Help &amp; support'),'unconfigured support must not appear as a permanent customer tab');
assert(dashboard.includes("include('_nav',{active:'overview',showBenefits:referralsEnabled})"),'dashboard must use shared customer navigation with conditional benefits');
assert(onboarding.includes('Choose how you want to watch')&&onboarding.includes('Free Access always remains visible'),'customers without access must receive a focused choose-access onboarding page');
assert(dashboard.includes('Upgrade: changes immediately')&&dashboard.includes('scheduled for your next renewal'),'dashboard must disclose Stripe plan-change timing before checkout');
assert(dashboard.includes('Stop PayPal renewal first'),'dashboard must disclose active recurring PayPal plan-change constraint');
assert(!/provisioning source|server placement|reconciliation/i.test(dashboard),'dashboard exposes operator-only jargon');
assert(stremio.includes("include('_nav',{active:'overview',showBenefits:Boolean(portal.referralsEnabled&&portal.referralCode)})"),'Stremio-only dashboard must use shared navigation with conditional benefits');
assert(customerPortalCss.includes('.accountHero')&&customerPortalCss.includes('.overviewGrid')&&customerPortalCss.includes('.metricCard')&&customerPortalCss.includes('.notice.error'),'customer dashboard hero, metrics and warning surfaces must be styled');
assert(!stremio.includes('style="font-size:20px"'),'Stremio dashboard should use customer CSS classes instead of inline metric sizing');
assert(history.includes("customerNav.nav('plans')"),'billing history must use shared navigation');
assert((router.includes('createCustomerActivityRouter')||customerComposition.includes('createCustomerActivityRouter'))&&activity.includes("r.get('/account/activity'"),'customer Activity navigation must have a mounted /account/activity route');
assert(/\/account\/trial\/start[\s\S]*welcome=1/.test(acquisition),'trial completion must enter welcome flow through the dedicated acquisition router');
assert(/\/account\/claim-free\/:planCode[\s\S]*welcome=1/.test(acquisition),'Free Access completion must enter welcome flow through the dedicated acquisition router');
assert(paymentReturn.includes('/account?welcome=1'),'PayPal completion must enter welcome flow');
assert(checkout.includes('/account?welcome=1&message=Payment%20received.'),'Stripe completion must enter welcome flow');
assert(storefront.includes('/account/register?intent=free'),'public Free Access CTA must carry explicit free intent into registration');
assert(pending.includes('FREE_HOLD_MINUTES=20')&&pending.includes('free_access_registration_reservations'),'verified Free Access registration must create a real expiring capacity hold');
assert(capacity.includes('free_access_registration_reservations')&&capacity.includes('reserved'),'plan capacity must count live registration holds');
assert(publicAuth.includes('await establish(req,created)')&&publicAuth.includes('activateRequestedFreeAccess(created)'),'verified registration must establish the customer session and continue onboarding automatically');
assert(publicAuth.includes('hold expired before verification'),'expired Free Access holds must preserve the new account and explain the next step');
console.log('customer portal IA smoke: ok');
